LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY MUXB IS
	PORT(B1, B2, B3, B4, B5: IN STD_LOGIC_VECTOR(3 DOWNTO 0);
		SEL: IN INTEGER RANGE 0 TO 4;
	     B: OUT STD_LOGIC_VECTOR(3 DOWNTO 0)); 
END ENTITY;

ARCHITECTURE BEAS OF MUXB IS
BEGIN
PROCESS(SEL)
	BEGIN
			CASE SEL	 IS
				WHEN 0 => B <= B1; -- 0
				WHEN 1 => B <= B2; -- 1
				WHEN 2 => B <= B3; -- 2
				WHEN 3 => B <= B4; -- 3 
				WHEN 4 => B <= B5; -- 4
			END CASE;
END PROCESS;
END BEAS;
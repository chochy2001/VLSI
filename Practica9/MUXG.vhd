LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY MUXG IS
	PORT(G1, G2, G3, G4, G5: IN STD_LOGIC_VECTOR(3 DOWNTO 0);
		SEL: IN INTEGER RANGE 0 TO 4;
	     G: OUT STD_LOGIC_VECTOR(3 DOWNTO 0)); 
END ENTITY;

ARCHITECTURE BEAS OF MUXG IS
BEGIN
PROCESS(SEL)
	BEGIN
			CASE SEL	 IS
				WHEN 0 => G <= G1; -- 0
				WHEN 1 => G <= G2; -- 1
				WHEN 2 => G <= G3; -- 2
				WHEN 3 => G <= G4; -- 3 
				WHEN 4 => G <= G5; -- 4
			END CASE;
END PROCESS;
END BEAS;
LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY MUXR IS
	PORT(R1, R2, R3, R4, R5: IN STD_LOGIC_VECTOR(3 DOWNTO 0);
		SEL: IN INTEGER RANGE 0 TO 4;
	     R: OUT STD_LOGIC_VECTOR(3 DOWNTO 0)); 
END ENTITY;

ARCHITECTURE BEAS OF MUXR IS
BEGIN
PROCESS(SEL)
	BEGIN
			CASE SEL	 IS
				WHEN 0 => R <= R1; -- 0
				WHEN 1 => R <= R2; -- 1
				WHEN 2 => R <= R3; -- 2
				WHEN 3 => R <= R4; -- 3 
				WHEN 4 => R <= R5; -- 4
			END CASE;
END PROCESS;
END BEAS;
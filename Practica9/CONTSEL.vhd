LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY CONTSEL IS
	PORT(CLK: IN STD_LOGIC;
		 SEL: BUFFER INTEGER RANGE 0 TO 4);
END ENTITY;

ARCHITECTURE BEAS OF CONTSEL IS
BEGIN

	PROCESS(CLK)
	BEGIN
		IF FALLING_EDGE (CLK) THEN
			IF SEL = 4 THEN
				SEL <= 0;
			ELSE
				SEL <= SEL + 1;
			END IF;
		END IF;
	END PROCESS;
END BEAS;
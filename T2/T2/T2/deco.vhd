LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY deco IS
PORT(
  NUM: in INTEGER RANGE 0 to 9;
  HAB: in STD_LOGIC; 
  SEG: OUT STD_LOGIC_VECTOR(7 DOWNTO 0)
);
END deco;

ARCHITECTURE am OF deco IS
BEGIN
PROCESS(NUM, HAB)
BEGIN
  IF HAB = '1' THEN
    CASE NUM IS
      WHEN 0 => SEG <= "00000011";
      WHEN 1 => SEG <= "10011111";
      WHEN 2 => SEG <= "00100101";
      WHEN 3 => SEG <= "00001101";
      WHEN 4 => SEG <= "10011001";
      WHEN 5 => SEG <= "01001001";
      WHEN 6 => SEG <= "01000001";
      WHEN 7 => SEG <= "00011101";
      WHEN 8 => SEG <= "00000001";
      WHEN OTHERS => SEG <= "00001001"; 
    END CASE;
  ELSE
    SEG <= "11111111"; -- Todos los segmentos apagados
  END IF; 
END PROCESS;
end am;
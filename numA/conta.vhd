LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.NUMERIC_STD.ALL;
USE IEEE.STD_LOGIC_UNSIGNED.ALL;

ENTITY conta IS
	PORT(CLK: IN STD_LOGIC;
              COUNT: BUFFER INTEGER RANGE 0 TO 15);
END ENTITY;

ARCHITECTURE BEAS OF conta IS
BEGIN

	PROCESS(CLK)
	BEGIN
		IF RISING_EDGE(CLK) THEN
			IF COUNT = 15 THEN
				COUNT <= 0;
			ELSE
				COUNT <= COUNT + 1;
			END IF;
		END IF;
	END PROCESS;
	
END BEAS;